export const crawlSubtasks = sqliteTable(
  'crawl_subtasks',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    taskId: integer('task_id').notNull().references(() => crawlTasks.id, { onDelete: 'cascade' }),
    taskType: text('task_type', {
      enum: [
        'fetch_states',
        'fetch_names',
        'fetch_addresses',
        'fetch_mailbox_numbers',
        'sync_smarty',
      ],
    }).notNull(),
    executionStatus: text('execution_status', {
      enum: ['pending', 'running', 'paused', 'completed'],
    }).notNull().default('pending'),
    resultStatus: text('result_status', { enum: ['success', 'failed', 'stopped'] }),
    errorMessage: text('error_message'),
    createdAt: text('created_at').notNull().default(sql`CURRENT_TIMESTAMP`),
    updatedAt: text('updated_at').notNull().default(sql`CURRENT_TIMESTAMP`),
  },
  (table) => [
    index('crawl_subtasks_task_id_idx').on(table.taskId),
    index('crawl_subtasks_task_type_idx').on(table.taskType),
    index('crawl_subtasks_execution_status_idx').on(table.executionStatus),
    index('crawl_subtasks_result_status_idx').on(table.resultStatus),
    check('crawl_subtasks_task_type_check', sql`${table.taskType} IN ('fetch_states', 'fetch_names', 'fetch_addresses', 'fetch_mailbox_numbers', 'sync_smarty')`),
    check('crawl_subtasks_execution_status_check', sql`${table.executionStatus} IN ('pending', 'running', 'paused', 'completed')`),
    check('crawl_subtasks_result_status_check', sql`${table.resultStatus} IS NULL OR ${table.resultStatus} IN ('success', 'failed', 'stopped')`),
  ],
);

